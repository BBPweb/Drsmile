  const faqItems = document.querySelectorAll('.faq-item');
  faqItems.forEach((item) => {
    const button = item.querySelector('.faq-toggle');
    const content = item.querySelector('.faq-content');

    const setOpenState = (open) => {
      item.classList.toggle('is-open', open);
      button.setAttribute('aria-expanded', String(open));
      content.style.maxHeight = open ? `${content.scrollHeight + 24}px` : '0px';
    };

    button.addEventListener('click', () => {
      const isOpen = item.classList.contains('is-open');

      faqItems.forEach((faq) => {
        const faqButton = faq.querySelector('.faq-toggle');
        const faqContent = faq.querySelector('.faq-content');
        faq.classList.remove('is-open');
        faqButton.setAttribute('aria-expanded', 'false');
        faqContent.style.maxHeight = '0px';
      });

      if (!isOpen) {
        setOpenState(true);
      }
    });

    if (item.classList.contains('is-open')) {
      setOpenState(true);
    }
  });

  const compareRange = document.querySelector('.compare-range');
  const compareOverlay = document.querySelector('.compare-overlay');
  const compareDivider = document.querySelector('.compare-divider');

  if (compareRange && compareOverlay && compareDivider) {
    const updateCompare = (value) => {
      const percent = Math.min(100, Math.max(0, Number(value) || 0));
      compareOverlay.style.width = `${percent}%`;
      compareDivider.style.left = `${percent}%`;
    };

    compareRange.addEventListener('input', (event) => updateCompare(event.target.value));
    updateCompare(compareRange.value);
  }
